// Builds supabase/seed.sql from assets/data/questions.json.
// Run: node tool/build_seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const qs = JSON.parse(readFileSync(new URL('../assets/data/questions.json', import.meta.url), 'utf8'));
const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;

// Deterministic shuffle so the correct answer is not always option A.
let seed = 42;
const rand = () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);

const rows = qs.map((q) => {
  const opts = [q.a, ...q.w];
  for (let i = opts.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [opts[i], opts[j]] = [opts[j], opts[i]];
  }
  const json = JSON.stringify(opts);
  return `  (${lit(q.c)}, ${lit(q.q)}, ${lit(json)}::jsonb, ${opts.indexOf(q.a)})`;
});

// Adds only questions that are not in the bank yet, so it is safe to run again
// after adding questions (and it keeps who-has-seen-what history intact).
// To change an existing question, delete its row first.
const sql = `-- Generated by tool/build_seed.mjs from assets/data/questions.json. Do not edit.
-- Safe to run more than once: only new questions are added.
insert into public.questions (category, stem, options, correct_index, source)
select v.category, v.stem, v.options, v.correct_index, 'curated'
from (values
${rows.join(',\n')}
) as v (category, stem, options, correct_index)
where not exists (
  select 1 from public.questions x where md5(lower(x.stem)) = md5(lower(v.stem))
);
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`seed.sql: ${rows.length} questions`);
